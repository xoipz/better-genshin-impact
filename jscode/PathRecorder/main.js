// 注册快捷键
function registerHotkeys() {
    hook.OnKeyDown((keyCode) => {
        switch (keyCode) {
            case keyRecord:
                startWithTp = false;
                toggleRecording();
                break;
            case keyRecordTp:
                startWithTp = true;
                toggleRecording();
                break;
            case keySplit:
                splitSegment();
                break;
            case keyOcr:
                handleDialogue();
                break;
            case keyFight:
                handleFight();
                break;
            case keyExport:
                handleEndRecording();
                break;
            case 'F12':
                toggleHUD();
                break;
        }
    });
}

