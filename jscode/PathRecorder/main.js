// 保存当前路径到文件
async function saveCurrentPath() {
    if (currentTrackData.positions.length === 0) return null;

    // 路径优化
    await processTrackData();

    const filename = `${questName}-${currentStepIndex}.json`;
    const fullFolder = `process/${questLocation}/${questName}`;
    const fullPath = `${fullFolder}/${filename}`;

    // 更新文件头信息
    currentTrackData.info.name = `${questName}-${currentStepIndex}`;

    file.writeTextSync(fullPath, JSON.stringify(currentTrackData, null, 2));

    // 重置数据
    currentTrackData.positions = [];
    lastPosition = null;
    currentStepIndex++;

    return filename;
}

// 保存process.json
function saveProcessData() {
    const processPath = `process/${questLocation}/${questName}/process.json`;
    try {
        const processText = processData.join('\n');
        const success = file.writeTextSync(processPath, processText);
        if (success) {
            log.info(`process.json 已保存`);
        }
        return success;
    } catch (error) {
        log.error(`保存process.json失败: ${error.message}`);
        return false;
    }
}

// 处理收集到的路径数据
async function processTrackData() {
    log.info("处理路径数据...");

    // 1. 先优化点
    optimizePathPoints();

    // 2. 处理移动模式
    processMoveModes();

    // 3. 清理临时状态属性
    for (const pos of currentTrackData.positions) {
        delete pos.state;
        delete pos.timestamp;
        delete pos.__climb_points_count;
    }

    log.info("路径数据处理完成");
}

// 完整的移动模式处理
function processMoveModes() {
    log.info("处理移动模式和动作...");

    const positions = currentTrackData.positions;
    if (!positions || positions.length === 0) return;

    // 重置动作（保留 optimize=false 的点）
    for (const pos of positions) {
        if (pos.optimize !== false) {
            pos.action = "";
        }
    }

    // 分段处理飞行/游泳/攀爬
    let i = 0;
    while (i < positions.length) {
        const currentState = positions[i].state;

        // 飞行段：设置 fly 模式，终点添加 stop_flying
        if (currentState === MOVE_STATE.FLY) {
            let end = i;
            while (end + 1 < positions.length && positions[end + 1].state === MOVE_STATE.FLY) end++;
            for (let k = i; k <= end; k++) positions[k].move_mode = MOVE_MODES.FLY;
            positions[end].action = "stop_flying";
            log.debug(`飞行段: ${i} - ${end}, 添加stop_flying`);
            i = end + 1;
            continue;
        }

        // 游泳段：设置 swim 模式
        if (currentState === MOVE_STATE.SWIM) {
            let end = i;
            while (end + 1 < positions.length && positions[end + 1].state === MOVE_STATE.SWIM) end++;
            for (let k = i; k <= end; k++) positions[k].move_mode = MOVE_MODES.SWIM;
            log.debug(`游泳段: ${i} - ${end}`);
            i = end + 1;
            continue;
        }

        // 攀爬段：根据时长决定 jump 或 climb
        if (currentState === MOVE_STATE.CLIMB) {
            let end = i;
            while (end + 1 < positions.length && positions[end + 1].state === MOVE_STATE.CLIMB) end++;

            const climbPointsCount = positions[i].__climb_points_count || (end - i + 1);
            const climbDurationSeconds = climbPointsCount * 0.9;
            const climbMode = climbDurationSeconds < 15 ? MOVE_MODES.JUMP : MOVE_MODES.CLIMB;

            for (let k = i; k <= end; k++) positions[k].move_mode = climbMode;
            log.debug(`攀爬段: ${i} - ${end}, 时长=${climbDurationSeconds.toFixed(1)}s, 模式=${climbMode}`);

            // 长攀爬前回溯15单位，将dash改为walk
            if (climbMode === MOVE_MODES.CLIMB) {
                let backDistAccum = 0;
                for (let j = i - 1; j >= 0; j--) {
                    const segDist = distance(
                        { x: positions[j + 1].x, y: positions[j + 1].y },
                        { x: positions[j].x, y: positions[j].y }
                    );
                    backDistAccum += segDist;
                    if (backDistAccum >= 15) break;
                    if (positions[j].move_mode === MOVE_MODES.DASH) {
                        positions[j].move_mode = MOVE_MODES.WALK;
                    }
                }
            }

            i = end + 1;
            continue;
        }

        i++;
    }

    // 未设置模式的点根据距离判断dash/walk
    for (let idx = 0; idx < positions.length; idx++) {
        if (!positions[idx].move_mode || positions[idx].move_mode === "") {
            if (idx === 0) {
                positions[idx].move_mode = MOVE_MODES.WALK;
                continue;
            }
            const prev = positions[idx - 1];
            const dist = distance({ x: positions[idx].x, y: positions[idx].y }, { x: prev.x, y: prev.y });
            positions[idx].move_mode = dist > 10 ? MOVE_MODES.DASH : MOVE_MODES.WALK;
        }
    }
}

// 路径优化
function optimizePathPoints() {
    const positions = currentTrackData.positions;
    if (positions.length <= 2) return;

    const originalPoints = positions.map((p, index) => ({
        index: index,
        x: p.x,
        y: p.y,
        state: p.state
    }));

    // RDP简化
    const pointsForRdp = originalPoints.map(p => ({ x: p.x, y: p.y }));
    const simplified = rdp(pointsForRdp, 2.0);

    // 找出保留的点索引
    let keptIndices = simplified.map(sp => {
        return originalPoints.findIndex(op => op.x === sp.x && op.y === sp.y);
    }).filter(idx => idx !== -1);

    // 分段扫描，确保保留状态转换点
    const segments = [];
    let segStart = 0;
    for (let i = 1; i < originalPoints.length; i++) {
        if (originalPoints[i].state !== originalPoints[i - 1].state) {
            segments.push({ state: originalPoints[segStart].state, start: segStart, end: i - 1 });
            segStart = i;
        }
    }
    segments.push({ state: originalPoints[segStart].state, start: segStart, end: originalPoints.length - 1 });

    // 强制保留首尾
    if (!keptIndices.includes(0)) keptIndices.push(0);
    if (!keptIndices.includes(originalPoints.length - 1)) keptIndices.push(originalPoints.length - 1);

    // 强制保留传送点和不可优化点
    for (let idx = 0; idx < positions.length; idx++) {
        const pos = positions[idx];
        if (pos.type === "teleport" || pos.optimize === false) {
            if (!keptIndices.includes(idx)) {
                keptIndices.push(idx);
            }
        }
    }

    // 保留状态分段的起止点
    for (const seg of segments) {
        if (seg.state === MOVE_STATE.FLY || seg.state === MOVE_STATE.SWIM) {
            if (!keptIndices.includes(seg.start)) keptIndices.push(seg.start);
            if (!keptIndices.includes(seg.end)) keptIndices.push(seg.end);
        } else if (seg.state === MOVE_STATE.CLIMB) {
            if (!keptIndices.includes(seg.start)) keptIndices.push(seg.start);
            if (!keptIndices.includes(seg.end)) keptIndices.push(seg.end);
            // 移除攀爬段中间点
            keptIndices = keptIndices.filter(idx => !(idx > seg.start && idx < seg.end));
            // 记录攀爬点数
            positions[seg.start].__climb_points_count = seg.end - seg.start + 1;
        }
    }

    // 去重排序
    keptIndices = Array.from(new Set(keptIndices)).sort((a, b) => a - b);

    // 创建新数组
    const newPositions = keptIndices.map(idx => ({ ...positions[idx] }));
    newPositions.forEach((pos, idx) => { pos.id = idx + 1; });

    currentTrackData.positions = newPositions;
    log.info(`路径优化: ${positions.length} → ${newPositions.length} 个点`);
}

// 主循环
async function mainLoop() {
    while (cycleCount < MAX_RECORDING_CYCLES) {
        cycleCount++;

        // 每1000次输出进度
        if (cycleCount % 1000 === 0) {
            log.info(`系统运行: ${cycleCount}/${MAX_RECORDING_CYCLES} (${((cycleCount / MAX_RECORDING_CYCLES) * 100).toFixed(1)}%)`);
        }

        try {
            // 1. 处理 HTML 指令
            await handleClientActions();

            // 2. 检测界面状态 (仅在需要时)
            let elementState = ELEMENT_STATE.MAINUI;
            try {
                elementState = await checkElementState();
            } catch (stateErr) {
                // 界面检测失败时使用默认值，避免阻塞
            }

            // 追踪地图状态
            if (elementState === ELEMENT_STATE.MAP) {
                wasInMap = true;
            } else if (wasInMap && !justExitedMap) {
                justExitedMap = true;
                wasInMap = false;
                log.info("检测到离开地图界面，设置传送检测标志");
            }

            // 3. 剧情界面处理
            if (elementState === ELEMENT_STATE.Story) {
                if (isRecording) {
                    log.info("录制中检测到剧情界面");
                    await handleStoryInterface();
                } else {
                    log.info("非录制状态检测到剧情界面，等待返回主界面");
                    await waitForMainUI();
                }
            }

            // 4. 录制逻辑
            if (isRecording && !isPaused) {
                try {
                    if (isInMainUI()) {
                        await recordPosition();
                    }
                } catch (recErr) {
                    // 录制出错时继续循环
                }
            }

            // 5. 更新HUD
            if (Date.now() - lastUpdateHUD > 500) {
                await updateHUD();
                lastUpdateHUD = Date.now();
            }
        } catch (e) {
            log.error("MainLoop Error: " + e.message);
        }

        // 确保每次循环都有延迟，避免死循环
        await sleep(500);
    }

    // 达到最大循环次数
    log.warn(`已达到最大运行次数限制 (${MAX_RECORDING_CYCLES})，自动保存并结束`);
    if (isRecording && currentTrackData.positions.length > 0) {
        const filename = await saveCurrentPath();
        if (filename) {
            processData.push(`地图追踪 ${filename}`);
            saveProcessData();
        }
    }
}

// 记录坐标
async function recordPosition() {
    try {
        const position = genshin.getPositionFromMap();
        if (position.X === 0 && position.Y === 0) return;

        // 距离判定
        let dist = 0;
        if (lastPosition) {
            dist = distance({ x: position.X, y: position.Y }, lastPosition);
            if (dist < 1.0) return; // 距离太近不记录
        }

        // 检测移动状态
        const moveState = await checkAbnormalState();

        let pointType = "path";
        let optimizeFlag = true;

        // 从地图退出后的传送检测
        if (justExitedMap) {
            log.info(`刚从地图返回，检测首个点，距离: ${dist.toFixed(2)}`);

            if (dist > TELEPORT_THRESHOLD) {
                log.info("检测为传送点，获取精确坐标...");

                // 按M键打开大地图
                keyPress("M");
                await sleep(500);

                let bigMapPosition = null;
                let retryCount = 0;

                while (retryCount < 3 && !bigMapPosition) {
                    try {
                        bigMapPosition = genshin.getPositionFromBigMap();
                        if (bigMapPosition && bigMapPosition.X !== 0 && bigMapPosition.Y !== 0) {
                            log.info(`大地图精确坐标: (${bigMapPosition.X.toFixed(3)}, ${bigMapPosition.Y.toFixed(3)})`);
                            position.X = bigMapPosition.X;
                            position.Y = bigMapPosition.Y;
                            break;
                        } else {
                            throw new Error("获取到无效坐标");
                        }
                    } catch (error) {
                        retryCount++;
                        if (retryCount < 3) await sleep(200);
                    }
                }

                await genshin.returnMainUi();
                await sleep(100);

                pointType = "teleport";
                optimizeFlag = false;
            }

            justExitedMap = false;
        } else if (dist > ANOMALY_THRESHOLD && lastPosition) {
            // 异常距离检测（非地图退出情况）
            log.warn(`异常距离: ${dist.toFixed(2)} > ${ANOMALY_THRESHOLD}，可能是传送`);
            await checkTeleport();
            return;
        }

        // 构建点数据
        const point = {
            id: currentTrackData.positions.length + 1,
            x: position.X,
            y: position.Y,
            action: "",
            move_mode: "dash",
            action_params: "",
            type: pointType,
            state: moveState,
            timestamp: Date.now()
        };

        if (!optimizeFlag) {
            point.optimize = false;
        }

        // 处理移动模式
        if (moveState === MOVE_STATE.FLY) point.move_mode = "fly";
        if (moveState === MOVE_STATE.CLIMB) point.move_mode = "climb";
        if (moveState === MOVE_STATE.SWIM) point.move_mode = "swim";

        currentTrackData.positions.push(point);
        lastPosition = { x: position.X, y: position.Y };

        log.debug(`记录点 #${point.id}: (${point.x.toFixed(1)}, ${point.y.toFixed(1)}) 状态=${moveState}`);

    } catch (e) {
        log.error("recordPosition Error: " + e.message);
    }
}

// 智能传送检测
async function checkTeleport() {
    if (!lastPosition) return;

    const pos = genshin.getPositionFromMap();
    const dist = distance({ x: pos.X, y: pos.Y }, lastPosition);

    if (dist > TELEPORT_THRESHOLD) {
        log.warn(`传送检测: 距离跳变 ${dist.toFixed(1)}m`);

        // 保存当前路径
        if (currentTrackData.positions.length > 0) {
            const filename = await saveCurrentPath();
            if (filename) {
                addStepToList('move', `Path ${currentStepIndex - 1}`, filename);
                processData.push(`地图追踪 ${filename}`);
                saveProcessData();
            }
        }

        // 获取精确坐标
        keyPress("M");
        await sleep(600);

        let bigMapPosition = null;
        let retryCount = 0;

        while (retryCount < 3 && !bigMapPosition) {
            try {
                bigMapPosition = genshin.getPositionFromBigMap();
                if (bigMapPosition && bigMapPosition.X !== 0 && bigMapPosition.Y !== 0) {
                    break;
                }
                throw new Error("无效坐标");
            } catch (error) {
                retryCount++;
                if (retryCount < 3) await sleep(300);
            }
        }

        await genshin.returnMainUi();
        await sleep(200);

        // 添加传送点
        if (bigMapPosition && bigMapPosition.X !== 0) {
            lastPosition = { x: bigMapPosition.X, y: bigMapPosition.Y };

            const teleportPoint = {
                id: currentTrackData.positions.length + 1,
                x: bigMapPosition.X,
                y: bigMapPosition.Y,
                action: "",
                move_mode: "walk",
                action_params: "",
                type: "teleport",
                optimize: false,
                state: MOVE_STATE.NORMAL,
                timestamp: Date.now()
            };
            currentTrackData.positions.push(teleportPoint);
            log.info(`添加传送点: (${bigMapPosition.X.toFixed(1)}, ${bigMapPosition.Y.toFixed(1)})`);
        } else {
            lastPosition = { x: pos.X, y: pos.Y };
        }

        notification.send("检测到传送，已自动分段保存");
        updateHUD();
    }
}

// 处理客户端指令
async function handleClientActions() {
    try {
        const actionStr = await htmlPanel.eval(HUD_ID, "window.clientAction");
        let action = null;
        try {
            if (actionStr && actionStr !== "null") {
                action = JSON.parse(actionStr);
            }
        } catch (e) { }

        if (action) {
            log.info("Client Action: " + JSON.stringify(action));
            await htmlPanel.eval(HUD_ID, "window.clientAction = null");

            switch (action.type) {
                case 'delete_step':
                    const idx = steps.findIndex(s => s.id === action.id);
                    if (idx !== -1) {
                        steps.splice(idx, 1);
                        stepsDirty = true;
                        updateHUD();
                    }
                    break;
                case 'rename_step':
                    const step = steps.find(s => s.id === action.id);
                    if (step) {
                        step.name = action.newName;
                        stepsDirty = true;
                        updateHUD();
                    }
                    break;
                case 'update_task_name':
                    questName = action.name;
                    break;
                case 'undo':
                    if (steps.length > 0) {
                        steps.pop();
                        stepsDirty = true;
                        updateHUD();
                    }
                    break;
                case 'hide_ui':
                    toggleHUD();
                    break;
            }
        }
    } catch (e) { }
}

// 更新HUD状态
let isUpdatingHUD = false;

async function updateHUD() {
    if (isUpdatingHUD) return;
    isUpdatingHUD = true;

    try {
        updateKeysStatus();

        let displayPos = currentPos;
        if (!lastPosition) {
            try {
                const p = genshin.getPositionFromMap();
                if (p.X !== 0) displayPos = { x: p.X, y: p.Y };
            } catch (e) { }
        } else {
            displayPos = lastPosition;
        }
        currentPos = displayPos;

        // 提取路径点用于地图绘制 (最多保留最近100个点避免数据过大)
        const pathPoints = currentTrackData.positions.slice(-100).map(p => ({
            x: p.x,
            y: p.y,
            type: p.type || 'path'
        }));

        const stateData = {
            isRecording: isRecording,
            isPaused: isPaused,
            lastEndType: lastEndType,
            taskName: questName,
            currentCoords: { x: displayPos.x, y: displayPos.y },
            keys: keysConfig,
            cycleCount: cycleCount,
            pathPoints: pathPoints
        };

        if (steps.length !== lastSentStepCount || stepsDirty) {
            stateData.steps = steps.map(s => ({
                id: s.id,
                name: s.name,
                type: s.type,
                start: s.start,
                end: s.end
            }));
            lastSentStepCount = steps.length;
            stepsDirty = false;
        }

        const newStateStr = JSON.stringify(stateData);
        if (newStateStr !== lastSentHudData) {
            try {
                await htmlPanel.eval(HUD_ID, `updateState(${newStateStr})`);
                lastSentHudData = newStateStr;
            } catch (e) { }
        }
    } finally {
        isUpdatingHUD = false;
    }
}

// 脚本结束清理
function cleanUp() {
    if (hook) hook.Dispose();
    htmlPanel.closeAll();

    if (processData.length > 1) {
        saveProcessData();
        log.info("Final process.json saved.");
    }
}

