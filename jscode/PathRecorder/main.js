// 脚本结束清理
function cleanUp() {
    if (hook) hook.Dispose();
    htmlPanel.closeAll();

    // 生成最终的 process.json
    if (steps.length > 0) {
        let processLines = [`作者：${author}`];
        steps.forEach(step => {
            if (step.type === 'path') {
                processLines.push(`地图追踪 ${step.data}`);
            } else if (step.type === 'fight') {
                processLines.push(`战斗`);
            } else if (step.type === 'dialogue') {
                processLines.push(step.data); // data is "Dialogue NPC" or just "Dialogue"
            }
        });

        const processPath = `process/${questLocation}/${questName}/process.json`;
        file.WriteTextSync(processPath, processLines.join('\n'));
        log.info(`Final process.json saved to ${processPath}`);
    }
}


