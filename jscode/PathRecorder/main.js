// 切换录制状态 (暂停/恢复)
async function toggleRecording() {
    if (isRecording) {
        // 正在录制 -> 暂停
        await handlePause();
    } else {
        // 未录制/已暂停 -> 开始/恢复录制
        await handleResume();
    }
}

// 处理暂停
async function handlePause() {
    if (!isRecording) return;

    log.info("暂停录制...");

    // 保存当前路径
    if (currentTrackData.positions.length > 0) {
        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1}`, filename);
            processData.push(`地图追踪 ${filename}`);
        }
    }

    // 添加暂停标记
    processData.push("暂停");
    saveProcessData();

    addStepToList('pause', 'Paused', null);

    lastEndType = 'pause';
    isRecording = false;
    isPaused = true;

    updateHUD();
    log.info("录制已暂停，按 " + keyRecord + " 恢复");
}

// 处理恢复录制
async function handleResume() {
    log.info("恢复/开始录制...");

    // 确保在主界面
    if (!isInMainUI()) {
        await genshin.returnMainUi();
        await sleep(300);
    }

    if (!isInMainUI()) {
        log.warn("不在主界面，无法开始录制");
        return;
    }

    // 开始新的录制段
    await startNewRecording();

    isRecording = true;
    isPaused = false;
    lastEndType = null;

    updateHUD();

    const tpInfo = startWithTp ? " (起点为传送点)" : "";
    log.info(`录制已开始${tpInfo}，文件段: ${currentStepIndex}`);
}

// 开始新的录制段
async function startNewRecording() {
    log.info("开始新的录制段...");

    // 获取当前位置
    const position = genshin.getPositionFromMap();
    if (position.X === 0 && position.Y === 0) {
        log.warn("无法获取当前位置");
        return;
    }

    // 判断起始点类型
    const isFirstRecording = (currentStepIndex === 1);
    let initialPointType = "path";

    if (startWithTp || (isFirstRecording && settings.forceTpFirst)) {
        initialPointType = "teleport";
        log.info("起点设置为传送点");
    }

    // 检测初始状态
    const initialState = await checkAbnormalState();

    // 添加起始点
    const startPoint = {
        id: currentTrackData.positions.length + 1,
        x: position.X,
        y: position.Y,
        action: "",
        move_mode: "walk",
        action_params: "",
        type: initialPointType,
        state: initialState,
        timestamp: Date.now()
    };

    if (initialPointType === "teleport") {
        startPoint.optimize = false;
    }

    currentTrackData.positions.push(startPoint);
    lastPosition = { x: position.X, y: position.Y };

    log.info(`新录制段开始: 类型=${initialPointType}, 坐标=(${position.X.toFixed(1)}, ${position.Y.toFixed(1)})`);
}

// 分段/保存
async function splitSegment() {
    if (!isRecording) {
        log.warn("未在录制状态，无法分段");
        return;
    }

    if (currentTrackData.positions.length > 0) {
        const startPos = currentTrackData.positions[0];
        const endPos = currentTrackData.positions[currentTrackData.positions.length - 1];

        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1}`, filename, startPos, endPos);
            processData.push(`地图追踪 ${filename}`);
            saveProcessData();
            log.info(`路径分段已保存: ${filename}`);
        }
    } else {
        log.warn("当前无路径数据可保存");
    }
}

// 处理对话功能 (完整版: OCR + 点击NPC)
async function handleDialogue() {
    if (!isRecording) {
        log.warn("未在录制状态，无法添加对话标记");
        return;
    }

    log.info("处理对话功能...");

    // 暂停录制
    const wasRecording = isRecording;
    isRecording = false;

    // 保存当前路径
    if (currentTrackData.positions.length > 0) {
        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1}`, filename);
            processData.push(`地图追踪 ${filename}`);
        }
    }

    // 确保在主界面
    await genshin.returnMainUi();
    await sleep(200);

    // 从游戏界面OCR提取NPC名称
    const npcName = await extractNPCNameFromTask();

    if (npcName) {
        log.info(`提取到NPC名称: ${npcName}`);

        // 尝试在对话区域找到并点击NPC
        const dialogRegion = { X: 1150, Y: 300, WIDTH: 350, HEIGHT: 400 };
        let dialogResults = await Utils.easyOCR(dialogRegion);

        for (let i = 0; i < dialogResults.count; i++) {
            let text = dialogResults[i].text;
            let res = dialogResults[i];
            if (text.includes(npcName)) {
                log.info(`点击NPC选项: ${text}`);
                keyDown("VK_MENU");
                await sleep(500);
                click(res.x, res.y);
                leftButtonClick();
                keyUp("VK_MENU");
                break;
            }
        }

        processData.push(`对话 ${npcName}`);
        addStepToList('ocr', `Talk: ${npcName}`, `对话 ${npcName}`);
    } else {
        log.warn("未能提取到NPC名称，添加默认对话指令");
        processData.push("对话");
        addStepToList('ocr', 'Dialogue', '对话');
    }

    // 按F键触发剧情
    log.info("按下F键触发剧情");
    keyPress("F");
    await sleep(500);

    saveProcessData();
    lastEndType = 'dialogue';

    updateHUD();
    log.info("对话标记已添加，等待剧情结束...");

    // 等待返回主界面
    await waitForMainUI();

    // 自动恢复录制
    if (wasRecording) {
        isRecording = true;
        lastEndType = null;
        startWithTp = false;
        await startNewRecording();
        log.info("从对话返回，自动恢复录制");
    }

    updateHUD();
}

// 处理战斗功能 (完整版: 标记 + 自动战斗)
async function handleFight() {
    if (!isRecording) {
        log.warn("未在录制状态，无法添加战斗标记");
        return;
    }

    log.info("处理战斗功能...");

    // 保存当前路径
    await genshin.returnMainUi();

    if (currentTrackData.positions.length > 0) {
        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1}`, filename);
            processData.push(`地图追踪 ${filename}`);
        }
    }

    // 添加战斗标记
    processData.push("战斗");
    saveProcessData();

    let pos = { x: 0, y: 0 };
    try {
        const p = genshin.getPositionFromMap();
        pos = { x: p.X, y: p.Y };
    } catch (e) { }

    addStepToList('fight', 'Combat Event', null, pos, pos);

    lastEndType = 'fight';
    isRecording = false;

    updateHUD();
    log.info("战斗标记已添加");

    // 如果启用自动战斗，执行战斗
    if (autoFight) {
        log.info("启动自动战斗...");
        try {
            await dispatcher.runTask(new SoloTask("AutoFight"));
            log.info("自动战斗完成");
        } catch (e) {
            log.error("自动战斗出错: " + e.message);
        }
    }

    // 等待返回主界面后，用户需要手动按键恢复录制
    log.info("战斗结束，按 " + keyRecord + " 恢复录制");
}

// 处理结束录制/导出
async function handleEndRecording() {
    log.info("结束录制并导出...");

    // 保存最后的路径
    if (currentTrackData.positions.length > 0) {
        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1}`, filename);
            processData.push(`地图追踪 ${filename}`);
        }
    }

    saveProcessData();
    lastEndType = 'save';
    isRecording = false;

    updateHUD();
    notification.send("PathRecorder: 录制已结束，process.json已保存");
    log.info("=== 录制已结束 ===");
    log.info(`保存位置: process/${questLocation}/${questName}/`);
    log.info(`共 ${steps.length} 个步骤`);
}

// 处理剧情界面
async function handleStoryInterface() {
    log.info("检测到剧情界面，处理特殊逻辑...");

    if (currentTrackData.positions.length > 0) {
        // 在最后一个路径点添加combat_script动作
        const lastIdx = currentTrackData.positions.length - 1;
        currentTrackData.positions[lastIdx].action = "combat_script";
        currentTrackData.positions[lastIdx].action_params = strategyScript;
        currentTrackData.positions[lastIdx].optimize = false;

        // 保存当前路径
        const filename = await saveCurrentPath();
        if (filename) {
            addStepToList('move', `Path ${currentStepIndex - 1} (Story)`, filename);
            processData.push(`地图追踪 ${filename}`);
            processData.push("等待返回主界面");
            saveProcessData();
        }
    }

    addStepToList('story', 'Wait MainUI', null);

    lastEndType = 'story';
    isRecording = false;

    log.info("剧情界面处理完成，等待返回主界面");
    updateHUD();

    // 等待返回主界面
    await waitForMainUI();

    // 自动恢复录制
    log.info("从剧情返回主界面，自动恢复录制");
    isRecording = true;
    lastEndType = null;
    startWithTp = false;
    lastPosition = null;
    await startNewRecording();

    updateHUD();
}

// 等待返回主界面
async function waitForMainUI() {
    log.info("等待返回主界面...");

    for (let i = 0; i < 1200; i++) { // 最多等待10分钟
        if (isInMainUI()) {
            log.info("已返回主界面");
            return true;
        }
        await sleep(500);
    }

    log.warn("等待返回主界面超时");
    return false;
}

// 添加步骤到列表
function addStepToList(type, name, data, startPos = null, endPos = null) {
    const step = {
        id: Date.now() + Math.random(),
        name: name,
        type: type,
        data: data,
        start: startPos ? [startPos.x?.toFixed(0) || '?', startPos.y?.toFixed(0) || '?'] : ['?', '?'],
        end: endPos ? [endPos.x?.toFixed(0) || '?', endPos.y?.toFixed(0) || '?'] : ['?', '?']
    };
    steps.push(step);
    stepsDirty = true;
}

