// 初始化
async function init() {
    log.info("Path Recorder Initializing...");

    // 0. 预热地图 (异步防止卡死)
    try {
        log.info("Warming up map resources (this may take a few seconds)...");
        await genshin.warmUpMapAsync();
        log.info("Map resources ready.");
    } catch (e) {
        log.error("Map warmup failed: " + e.message);
    }

    // 1. 创建HUD
    log.info("Creating HTML Panel...");
    htmlPanel.create(HUD_ID, HUD_WIDTH, HUD_HEIGHT);
    const htmlContent = file.readTextSync("status.html");

    log.info("Loading HTML Content...");
    htmlPanel.loadHtml(HUD_ID, htmlContent);

    // 等待 WebView2 初始化完成
    await sleep(500);

    // 设置HUD样式 (透明穿透 + 右侧停靠)
    // 注意：CSS中已设置 pointer-events: none 实现穿透，无需 SetLocked(true)，否则无法交互
    // 我们需要的是：背景透明，但列表区域可点击。这完全由HTML/CSS控制。
    htmlPanel.setLocked(HUD_ID, false); // 全局状态 - 适配新HTML
    htmlPanel.setPosition(HUD_ID, genshin.width - HUD_WIDTH - 20, 100);

    log.info("Showing HUD...");
    htmlPanel.show(HUD_ID);

    // 2. 注册键鼠钩子
    log.info("Registering hooks...");
    hook = new KeyMouseHook();
    registerHotkeys();

    // 3. 启动主循环
    log.info("Starting main loop...");
    await mainLoop();
}

// 注册快捷键
function registerHotkeys() {
    hook.OnKeyDown((keyCode) => {
        switch (keyCode) {
            case keyRecord:
                toggleRecording();
                break;
            case keySplit:
                splitSegment();
                break;
            case keyOcr:
                triggerOCR();
                break;
            case keyFight:
                addCombatMarker();
                break;
            case 'F12':
                toggleHUD();
                break;
        }
    });
}

