// 切换录制状态
function toggleRecording() {
    if (isPaused) {
        // 从暂停恢复
        isPaused = false;
        isRecording = true;
        log.info("Resumed recording.");
    } else {
        isRecording = !isRecording;
        if (isRecording) {
            log.info("Started recording.");
            // 每次开始录制时，重新获取当前位置作为起点
            lastPosition = null;
        } else {
            log.info("Stopped recording.");
        }
    }
    updateHUD();
}

// 分段/保存
async function splitSegment() {
    if (currentTrackData.positions.length > 0) {
        // 保存前的起点和终点
        const startPos = currentTrackData.positions[0];
        const endPos = currentTrackData.positions[currentTrackData.positions.length - 1];

        const filename = await saveCurrentPath();
        if (filename) {
            steps.push({
                id: Date.now(),
                name: `Path ${currentStepIndex - 1}`,
                type: 'move',
                data: filename,
                start: [startPos.x.toFixed(0), startPos.y.toFixed(0)],
                end: [endPos.x.toFixed(0), endPos.y.toFixed(0)]
            });
            updateHUD();
            log.info(`Segment saved: ${filename}`);
        }
    } else {
        log.warn("No path data to save.");
    }
}

