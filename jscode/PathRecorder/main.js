// 保存当前路径到文件
async function saveCurrentPath() {
    if (currentTrackData.positions.length === 0) return null;

    // 路径优化
    optimizePathPoints();

    const filename = `${questName}-${currentStepIndex}.json`;
    const fullFolder = `process/${questLocation}/${questName}`;
    const fullPath = `${fullFolder}/${filename}`;

    // 确保目录存在 (BGI会自动创建，这里是形式上的)
    // ...

    // 更新文件头信息的名称
    currentTrackData.info.name = `${questName}-${currentStepIndex}`;

    file.WriteTextSync(fullPath, JSON.stringify(currentTrackData, null, 2));

    // 重置数据
    currentTrackData.positions = [];
    lastPosition = null;
    currentStepIndex++;

    return filename;
}

// 路径优化 (复用AutoStoryTranscribe逻辑)
function optimizePathPoints() {
    const positions = currentTrackData.positions;
    if (positions.length <= 2) return;

    // 1. RDP 简化
    const pointsForRdp = positions.map(p => ({ x: p.x, y: p.y }));
    const simplified = rdp(pointsForRdp, 2.0); // epsilon = 2.0

    // 找出保留的索引
    let keptIndices = new Set([0, positions.length - 1]); // 必留起止点

    // 映射回原始索引
    simplified.forEach(sp => {
        // 简单查找（注意：这在有重复坐标时可能不精准，但在RDP上下文中通常可行）
        // 更严谨的做法是在rdp函数中保留索引，但这里复用现有逻辑
        const idx = positions.findIndex(p => p.x === sp.x && p.y === sp.y);
        if (idx !== -1) keptIndices.add(idx);
    });

    // 2. 状态保护 (飞行、游泳、传送点)
    for (let i = 0; i < positions.length; i++) {
        const p = positions[i];
        // 传送点必留
        if (p.type === 'teleport' || p.optimize === false) keptIndices.add(i);

        // 状态转折点必留 (例如 跑->飞)
        if (i > 0 && positions[i].state !== positions[i - 1].state) {
            keptIndices.add(i - 1);
            keptIndices.add(i);
        }
    }

    // 重建数组
    const newPositions = Array.from(keptIndices).sort((a, b) => a - b).map(idx => {
        const p = positions[idx];
        p.id = idx + 1; // 重置ID
        return p;
    });

    currentTrackData.positions = newPositions;
}


// 主循环
async function mainLoop() {
    while (true) {
        try {
            // 1. 处理 HTML 发来的指令
            await handleClientActions();

            // 2. 录制逻辑
            if (isRecording && !isPaused) {
                if (isInMainUI()) {
                    await recordPosition();
                    await checkTeleport();
                }
            }

            // 3. 更新 HUD (每500ms更新一次，避免过于频繁)
            if (Date.now() - lastUpdateHUD > 500) {
                await updateHUD();
                lastUpdateHUD = Date.now();
            }
        } catch (e) {
            log.error("MainLoop Error: " + e.message);
        }

        await sleep(500);
    }
}

// 记录坐标
async function recordPosition() {
    try {
        const pos = genshin.getPositionFromMap();
        if (pos.X === 0 && pos.Y === 0) return;

        // 距离判定
        let dist = 0;
        if (lastPosition) {
            dist = distance({ x: pos.X, y: pos.Y }, lastPosition);
            if (dist < 1.0) return; // 距离太近不记录
        }

        // 状态判定 (复用 detection.js)
        const moveState = await checkAbnormalState();

        // 构建点数据
        const point = {
            id: currentTrackData.positions.length + 1,
            x: pos.X,
            y: pos.Y,
            action: "",
            move_mode: "walk", // 稍后在优化阶段可以 refined
            action_params: "",
            type: "path",
            state: moveState, // 临时保存用于优化
            timestamp: Date.now()
        };

        // 处理移动模式
        if (moveState === MOVE_STATE.FLY) point.move_mode = "fly";
        if (moveState === MOVE_STATE.CLIMB) point.move_mode = "climb";
        if (moveState === MOVE_STATE.SWIM) point.move_mode = "swim";
        // 普通 walk/dash 在优化阶段处理，暂记为 walk

        currentTrackData.positions.push(point);
        lastPosition = { x: pos.X, y: pos.Y };

        log.debug(`Recorded point: ${point.id} (${point.x.toFixed(1)}, ${point.y.toFixed(1)}) State: ${moveState}`);

    } catch (e) {
        log.error("Record Error: " + e.message);
    }
}

// 智能传送检测
async function checkTeleport() {
    // 逻辑：如果上一帧显示在地图界面，这一帧回到了主界面 -> 标记潜在传送
    // 这里我们简化：如果在主界面，且距离上一点突变 > 50米 -> 判定为传送，自动暂停
    if (!lastPosition) return;

    const pos = genshin.getPositionFromMap();
    const dist = distance({ x: pos.X, y: pos.Y }, lastPosition);

    if (dist > TELEPORT_THRESHOLD) {
        log.warn(`Dist jump detected: ${dist.toFixed(1)}m. Auto-pausing for confirmation.`);

        // 自动暂停
        isPaused = true;
        isRecording = false; // 严格暂停

        // 可以在这里自动标记上一个点为传送点，或者等待用户操作
        // 这里选择：弹出提示（通过HUD状态变色），用户手动F8恢复时，我们会重置lastPosition，
        // 这样下一次记录就是新的起点（传送后的点），这天然符合BGI路径逻辑（传送是断开的）。

        notification.Send("检测到长距离移动，录制已自动暂停。请按F8恢复录制。");
        updateHUD();
    }
}


// 处理客户端指令 (模拟双向通信)
async function handleClientActions() {
    try {
        // 读取 HTML 中的 window.clientAction 变量
        // log.debug("Evaluating window.clientAction...");
        const actionStr = await htmlPanel.eval(HUD_ID, "window.clientAction");
        let action = null;
        try {
            if (actionStr && actionStr !== "null") {
                action = JSON.parse(actionStr);
            }
        } catch (e) {
            // ignore parse error or null
        }

        if (action) {
            log.info("Client Action received: " + JSON.stringify(action));

            // 清除指令防止重复执行
            await htmlPanel.eval(HUD_ID, "window.clientAction = null");

            switch (action.type) {
                case 'delete_step':
                    const idx = steps.findIndex(s => s.id === action.id);
                    if (idx !== -1) {
                        steps.splice(idx, 1);
                        updateHUD();
                    }
                    break;
                case 'rename_step':
                    const step = steps.find(s => s.id === action.id);
                    if (step) {
                        step.name = action.newName;
                        updateHUD();
                    }
                    break;
                case 'update_task_name':
                    questName = action.name;
                    // updateHUD not needed as input handles itself, but good for sync
                    break;
                case 'undo':
                    // simple undo: pop last step
                    if (steps.length > 0) {
                        steps.pop();
                        updateHUD();
                    }
                    break;
                case 'hide_ui':
                    toggleHUD();
                    break;
            }
        }
    } catch (e) {
        // 忽略 eval 错误 (可能是窗口还没加载好)
    }
}

// 更新 HUD 状态 (改为 async 函数，正确 await eval 调用)
let isUpdatingHUD = false; // 防止重入

async function updateHUD() {
    // 防止重入：如果上一次更新还没完成，跳过本次
    if (isUpdatingHUD) return;
    isUpdatingHUD = true;

    try {
        updateKeysStatus();

        const pos = lastPosition || currentPos || { x: 0, y: 0 };
        // 如果没有 lastPosition (未录制), 获取当前位置用于显示
        let displayPos = pos;
        if (!lastPosition) {
            try {
                const p = genshin.getPositionFromMap();
                if (p.X !== 0) displayPos = { x: p.X, y: p.Y };
            } catch (e) { }
        }
        currentPos = displayPos;

        // 基础数据 (高频)
        const stateData = {
            isRecording: isRecording,
            taskName: questName,
            currentCoords: { x: displayPos.x, y: displayPos.y },
            keys: keysConfig
        };

        // 增量更新检测：只有当步骤数量发生变化时才发送步骤列表
        const currentStepCount = steps.length;

        // 如果有 dirty 标记 (e.g. rename) 或者长度变化
        if (currentStepCount !== lastSentStepCount || stepsDirty) {
            stateData.steps = steps.map(s => ({
                id: s.id,
                name: s.name,
                type: s.type,
                start: s.start,
                end: s.end
            }));
            lastSentStepCount = currentStepCount;
            stepsDirty = false;
        }

        const newStateStr = JSON.stringify(stateData);
        if (newStateStr !== lastSentHudData) {
            try {
                await htmlPanel.eval(HUD_ID, `updateState(${newStateStr})`);
                lastSentHudData = newStateStr;
            } catch (e) {
                // 忽略 eval 错误 (可能是窗口还没加载好或已关闭)
            }
        }
    } finally {
        isUpdatingHUD = false;
    }
}

